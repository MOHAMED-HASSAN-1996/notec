export type Lang = "ar" | "en";

export function pluralize(
  n: number,
  lang: Lang,
  arForms: [string, string, string],
  enForms: [string, string],
): string {
  if (lang === "ar") {
    if (n === 1) return arForms[0];
    if (n === 2) return arForms[1];
    return arForms[2];
  }
  return n === 1 ? enForms[0] : enForms[1];
}

